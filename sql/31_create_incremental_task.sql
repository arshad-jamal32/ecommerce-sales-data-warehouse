
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 31: SNOWFLAKE TASK AUTOMATION
-- ============================================

-- 1. Create a triggered task
CREATE OR REPLACE TASK
    MY_FIRST_DB.SILVER.PRODUCT_INCREMENTAL_TASK

    WAREHOUSE = COMPUTE_WH

    WHEN SYSTEM$STREAM_HAS_DATA(
        'MY_FIRST_DB.SILVER.PRODUCTS_CHANGE_STREAM'
    )

AS

MERGE INTO
    MY_FIRST_DB.SILVER.DIM_PRODUCTS_INCREMENTAL_DEMO AS TARGET

USING
(
    SELECT
        PRODUCT_ID,
        CATEGORY_ID,
        CATEGORY_CODE,
        BRAND,
        BRAND_VARIANT_COUNT,
        BRAND_CONFLICT_FLAG
    FROM MY_FIRST_DB.SILVER.PRODUCTS_CHANGE_STREAM
    WHERE METADATA$ACTION = 'INSERT'
) AS SOURCE

ON TARGET.PRODUCT_ID = SOURCE.PRODUCT_ID

WHEN MATCHED THEN
    UPDATE SET
        TARGET.CATEGORY_ID = SOURCE.CATEGORY_ID,
        TARGET.CATEGORY_CODE = SOURCE.CATEGORY_CODE,
        TARGET.BRAND = SOURCE.BRAND,
        TARGET.BRAND_VARIANT_COUNT = SOURCE.BRAND_VARIANT_COUNT,
        TARGET.BRAND_CONFLICT_FLAG = SOURCE.BRAND_CONFLICT_FLAG

WHEN NOT MATCHED THEN
    INSERT
    (
        PRODUCT_ID,
        CATEGORY_ID,
        CATEGORY_CODE,
        BRAND,
        BRAND_VARIANT_COUNT,
        BRAND_CONFLICT_FLAG
    )
    VALUES
    (
        SOURCE.PRODUCT_ID,
        SOURCE.CATEGORY_ID,
        SOURCE.CATEGORY_CODE,
        SOURCE.BRAND,
        SOURCE.BRAND_VARIANT_COUNT,
        SOURCE.BRAND_CONFLICT_FLAG
    );


-- 2. Resume the task
ALTER TASK
    MY_FIRST_DB.SILVER.PRODUCT_INCREMENTAL_TASK
RESUME;


-- 3. Verify task details
SHOW TASKS IN SCHEMA MY_FIRST_DB.SILVER;
