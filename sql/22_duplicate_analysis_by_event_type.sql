
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 22: DUPLICATES BY EVENT TYPE
-- ============================================

WITH DUPLICATE_GROUPS AS
(
    SELECT
        EVENT_TYPE,
        COUNT(*) AS OCCURRENCES

    FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS

    GROUP BY
        EVENT_TIME,
        EVENT_TYPE,
        PRODUCT_ID,
        CATEGORY_ID,
        CATEGORY_CODE,
        BRAND,
        PRICE,
        USER_ID,
        USER_SESSION

    HAVING COUNT(*) > 1
)

SELECT
    EVENT_TYPE,

    COUNT(*) AS DUPLICATE_GROUPS,

    SUM(OCCURRENCES) AS TOTAL_ROWS_IN_DUPLICATE_GROUPS,

    SUM(OCCURRENCES - 1) AS EXTRA_DUPLICATE_ROWS,

    MAX(OCCURRENCES) AS MAX_OCCURRENCES

FROM DUPLICATE_GROUPS

GROUP BY EVENT_TYPE

ORDER BY EXTRA_DUPLICATE_ROWS DESC;
