
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 23: GOLD DUPLICATE KEY VALIDATION
-- ============================================

SELECT
    'DAILY_SALES' AS TABLE_NAME,
    COUNT(*) AS DUPLICATE_KEY_GROUPS
FROM
(
    SELECT SALES_DATE
    FROM MY_FIRST_DB.GOLD.DAILY_SALES
    GROUP BY SALES_DATE
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'PRODUCT_PERFORMANCE',
    COUNT(*)
FROM
(
    SELECT PRODUCT_ID
    FROM MY_FIRST_DB.GOLD.PRODUCT_PERFORMANCE
    GROUP BY PRODUCT_ID
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'CUSTOMER_BEHAVIOR',
    COUNT(*)
FROM
(
    SELECT USER_ID
    FROM MY_FIRST_DB.GOLD.CUSTOMER_BEHAVIOR
    GROUP BY USER_ID
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'CONVERSION_FUNNEL',
    CASE
        WHEN COUNT(*) = 1 THEN 0
        ELSE 1
    END
FROM MY_FIRST_DB.GOLD.CONVERSION_FUNNEL;
