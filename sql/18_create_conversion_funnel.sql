-- E-COMMERCE DATA WAREHOUSE
-- STEP 18: GOLD CONVERSION FUNNEL
-- ============================================

CREATE TABLE IF NOT EXISTS
    MY_FIRST_DB.GOLD.CONVERSION_FUNNEL
AS

WITH SESSION_FLAGS AS
(
    SELECT
        USER_SESSION,

        COUNT_IF(EVENT_TYPE = 'view') > 0
            AS HAS_VIEW,

        COUNT_IF(EVENT_TYPE = 'cart') > 0
            AS HAS_CART,

        COUNT_IF(EVENT_TYPE = 'purchase') > 0
            AS HAS_PURCHASE

    FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS

    WHERE USER_SESSION IS NOT NULL

    GROUP BY USER_SESSION
)

SELECT
    COUNT(*) AS TOTAL_SESSIONS_ANALYZED,

    COUNT_IF(HAS_VIEW)
        AS SESSIONS_WITH_VIEW,

    COUNT_IF(HAS_CART)
        AS SESSIONS_WITH_CART,

    COUNT_IF(HAS_PURCHASE)
        AS SESSIONS_WITH_PURCHASE,

    COUNT_IF(HAS_VIEW AND HAS_CART)
        AS SESSIONS_WITH_VIEW_AND_CART,

    COUNT_IF(HAS_VIEW AND HAS_CART AND HAS_PURCHASE)
        AS SESSIONS_COMPLETING_FUNNEL,

    ROUND(
        100.0 * COUNT_IF(HAS_VIEW AND HAS_CART)
        / NULLIF(COUNT_IF(HAS_VIEW), 0),
        2
    ) AS VIEW_TO_CART_RATE,

    ROUND(
        100.0 * COUNT_IF(HAS_VIEW AND HAS_CART AND HAS_PURCHASE)
        / NULLIF(COUNT_IF(HAS_VIEW AND HAS_CART), 0),
        2
    ) AS CART_TO_PURCHASE_RATE,

    ROUND(
        100.0 * COUNT_IF(HAS_VIEW AND HAS_CART AND HAS_PURCHASE)
        / NULLIF(COUNT_IF(HAS_VIEW), 0),
        2
    ) AS VIEW_TO_PURCHASE_RATE

FROM SESSION_FLAGS;
