
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 28: MERGE / UPSERT DEMONSTRATION
-- ============================================

-- 1. Create an isolated zero-copy clone
CREATE OR REPLACE TABLE
    MY_FIRST_DB.SILVER.DIM_PRODUCTS_MERGE_DEMO
CLONE
    MY_FIRST_DB.SILVER.DIM_PRODUCTS;


-- 2. MERGE source: one existing product + one new demo product
CREATE OR REPLACE TEMP TABLE
    MY_FIRST_DB.SILVER.MERGE_DEMO_SOURCE
AS

SELECT
    PRODUCT_ID,
    CATEGORY_ID,
    CATEGORY_CODE,
    'demo_brand_updated' AS BRAND,
    1 AS BRAND_VARIANT_COUNT,
    FALSE AS BRAND_CONFLICT_FLAG
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS
WHERE PRODUCT_ID = 1005115

UNION ALL

SELECT
    999999999999 AS PRODUCT_ID,
    NULL AS CATEGORY_ID,
    'demo_category' AS CATEGORY_CODE,
    'demo_brand' AS BRAND,
    1 AS BRAND_VARIANT_COUNT,
    FALSE AS BRAND_CONFLICT_FLAG;


-- 3. Perform MERGE
MERGE INTO MY_FIRST_DB.SILVER.DIM_PRODUCTS_MERGE_DEMO AS TARGET
USING MY_FIRST_DB.SILVER.MERGE_DEMO_SOURCE AS SOURCE
    ON TARGET.PRODUCT_ID = SOURCE.PRODUCT_ID

WHEN MATCHED THEN
    UPDATE SET
        TARGET.CATEGORY_ID = SOURCE.CATEGORY_ID,
        TARGET.CATEGORY_CODE = SOURCE.CATEGORY_CODE,
        TARGET.BRAND = SOURCE.BRAND,
        TARGET.BRAND_VARIANT_COUNT = SOURCE.BRAND_VARIANT_COUNT,
        TARGET.BRAND_CONFLICT_FLAG = SOURCE.BRAND_CONFLICT_FLAG

WHEN NOT MATCHED THEN
    INSERT (
        PRODUCT_ID,
        CATEGORY_ID,
        CATEGORY_CODE,
        BRAND,
        BRAND_VARIANT_COUNT,
        BRAND_CONFLICT_FLAG
    )
    VALUES (
        SOURCE.PRODUCT_ID,
        SOURCE.CATEGORY_ID,
        SOURCE.CATEGORY_CODE,
        SOURCE.BRAND,
        SOURCE.BRAND_VARIANT_COUNT,
        SOURCE.BRAND_CONFLICT_FLAG
    );


-- 4. Verify the updated existing product
SELECT *
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS_MERGE_DEMO
WHERE PRODUCT_ID = 1005115;


-- 5. Verify the newly inserted demo product
SELECT *
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS_MERGE_DEMO
WHERE PRODUCT_ID = 999999999999;


-- 6. Verify total row count
SELECT COUNT(*) AS TOTAL_PRODUCTS_AFTER_MERGE
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS_MERGE_DEMO;
