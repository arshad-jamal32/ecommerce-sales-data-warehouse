
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 26: SEQUENTIAL CONVERSION FUNNEL
-- ============================================

CREATE OR REPLACE TABLE
    MY_FIRST_DB.GOLD.CONVERSION_FUNNEL_SEQUENTIAL
AS

-- Stage 1: Find first view in each session
WITH SESSION_VIEWS AS
(
    SELECT
        USER_SESSION,
        MIN(EVENT_TIME) AS FIRST_VIEW_TIME
    FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS
    WHERE
        USER_SESSION IS NOT NULL
        AND EVENT_TYPE = 'view'
    GROUP BY USER_SESSION
),

-- Stage 2: Find a cart event strictly after the first view
SESSION_CARTS AS
(
    SELECT
        V.USER_SESSION,
        V.FIRST_VIEW_TIME,
        MIN(E.EVENT_TIME) AS FIRST_CART_AFTER_VIEW
    FROM SESSION_VIEWS V
    INNER JOIN MY_FIRST_DB.SILVER.CLEAN_EVENTS E
        ON V.USER_SESSION = E.USER_SESSION
    WHERE
        E.EVENT_TYPE = 'cart'
        AND E.EVENT_TIME > V.FIRST_VIEW_TIME
    GROUP BY
        V.USER_SESSION,
        V.FIRST_VIEW_TIME
),

-- Stage 3: Find a purchase strictly after that cart
SESSION_PURCHASES AS
(
    SELECT
        C.USER_SESSION,
        C.FIRST_VIEW_TIME,
        C.FIRST_CART_AFTER_VIEW,
        MIN(E.EVENT_TIME) AS FIRST_PURCHASE_AFTER_CART
    FROM SESSION_CARTS C
    INNER JOIN MY_FIRST_DB.SILVER.CLEAN_EVENTS E
        ON C.USER_SESSION = E.USER_SESSION
    WHERE
        E.EVENT_TYPE = 'purchase'
        AND E.EVENT_TIME > C.FIRST_CART_AFTER_VIEW
    GROUP BY
        C.USER_SESSION,
        C.FIRST_VIEW_TIME,
        C.FIRST_CART_AFTER_VIEW
),

-- Stage 4: Aggregate funnel metrics
FUNNEL_SUMMARY AS
(
    SELECT
        (SELECT COUNT(DISTINCT USER_SESSION)
         FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS
         WHERE USER_SESSION IS NOT NULL)
            AS TOTAL_SESSIONS_ANALYZED,

        (SELECT COUNT(*)
         FROM SESSION_VIEWS)
            AS SESSIONS_WITH_VIEW,

        (SELECT COUNT(*)
         FROM SESSION_CARTS)
            AS SESSIONS_WITH_VIEW_THEN_CART,

        (SELECT COUNT(*)
         FROM SESSION_PURCHASES)
            AS SESSIONS_COMPLETING_SEQUENTIAL_FUNNEL
)

SELECT
    TOTAL_SESSIONS_ANALYZED,
    SESSIONS_WITH_VIEW,
    SESSIONS_WITH_VIEW_THEN_CART,
    SESSIONS_COMPLETING_SEQUENTIAL_FUNNEL,

    ROUND(
        100.0 * SESSIONS_WITH_VIEW_THEN_CART
        / NULLIF(SESSIONS_WITH_VIEW, 0),
        2
    ) AS VIEW_TO_CART_RATE,

    ROUND(
        100.0 * SESSIONS_COMPLETING_SEQUENTIAL_FUNNEL
        / NULLIF(SESSIONS_WITH_VIEW_THEN_CART, 0),
        2
    ) AS CART_TO_PURCHASE_RATE,

    ROUND(
        100.0 * SESSIONS_COMPLETING_SEQUENTIAL_FUNNEL
        / NULLIF(SESSIONS_WITH_VIEW, 0),
        2
    ) AS VIEW_TO_PURCHASE_RATE

FROM FUNNEL_SUMMARY;
