-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 03: FILE FORMAT AND INTERNAL STAGE
-- ============================================

-- 1. Create CSV file format
CREATE FILE FORMAT IF NOT EXISTS
    MY_FIRST_DB.BRONZE.CSV_GZIP_FORMAT
    TYPE = CSV
    COMPRESSION = GZIP
    FIELD_DELIMITER = ','
    RECORD_DELIMITER = '\n'
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- 2. Create internal stage
CREATE STAGE IF NOT EXISTS
    MY_FIRST_DB.BRONZE.EVENTS_STAGE
    FILE_FORMAT = MY_FIRST_DB.BRONZE.CSV_GZIP_FORMAT;