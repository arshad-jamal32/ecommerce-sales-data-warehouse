-- STEP 13: CREATE PRODUCT DIMENSION
-- ============================================

CREATE TABLE IF NOT EXISTS
    MY_FIRST_DB.SILVER.DIM_PRODUCTS
AS

SELECT
    PRODUCT_ID,

    MIN(CATEGORY_ID) AS CATEGORY_ID,

    MIN(CATEGORY_CODE) AS CATEGORY_CODE,

    MIN(BRAND) AS BRAND,

    COUNT(DISTINCT BRAND) AS BRAND_VARIANT_COUNT,

    COUNT(DISTINCT BRAND) > 1 AS BRAND_CONFLICT_FLAG

FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS

GROUP BY PRODUCT_ID;