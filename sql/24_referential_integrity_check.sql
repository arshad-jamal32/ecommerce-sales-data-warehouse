-- E-COMMERCE DATA WAREHOUSE
-- STEP 24: REFERENTIAL INTEGRITY CHECK
-- ============================================

-- 1. Events with missing product dimension

SELECT
    'MISSING_PRODUCT_DIMENSION' AS CHECK_NAME,
    COUNT(*) AS FAILED_RECORDS
FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS E
LEFT JOIN MY_FIRST_DB.SILVER.DIM_PRODUCTS P
    ON E.PRODUCT_ID = P.PRODUCT_ID
WHERE P.PRODUCT_ID IS NULL

UNION ALL

-- 2. Events with missing user dimension

SELECT
    'MISSING_USER_DIMENSION',
    COUNT(*)
FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS E
LEFT JOIN MY_FIRST_DB.SILVER.DIM_USERS U
    ON E.USER_ID = U.USER_ID
WHERE U.USER_ID IS NULL;
