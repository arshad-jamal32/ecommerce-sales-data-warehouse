-- STEP 07: MISSING VALUES ANALYSIS
-- ============================================

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(EVENT_TIME IS NULL OR TRIM(EVENT_TIME) = '') AS MISSING_EVENT_TIME,

    COUNT_IF(EVENT_TYPE IS NULL OR TRIM(EVENT_TYPE) = '') AS MISSING_EVENT_TYPE,

    COUNT_IF(PRODUCT_ID IS NULL OR TRIM(PRODUCT_ID) = '') AS MISSING_PRODUCT_ID,

    COUNT_IF(CATEGORY_ID IS NULL OR TRIM(CATEGORY_ID) = '') AS MISSING_CATEGORY_ID,

    COUNT_IF(CATEGORY_CODE IS NULL OR TRIM(CATEGORY_CODE) = '') AS MISSING_CATEGORY_CODE,

    COUNT_IF(BRAND IS NULL OR TRIM(BRAND) = '') AS MISSING_BRAND,

    COUNT_IF(PRICE IS NULL OR TRIM(PRICE) = '') AS MISSING_PRICE,

    COUNT_IF(USER_ID IS NULL OR TRIM(USER_ID) = '') AS MISSING_USER_ID,

    COUNT_IF(USER_SESSION IS NULL OR TRIM(USER_SESSION) = '') AS MISSING_USER_SESSION

FROM MY_FIRST_DB.BRONZE.RAW_EVENTS;
