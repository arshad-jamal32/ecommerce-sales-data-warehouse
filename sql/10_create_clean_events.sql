-- E-COMMERCE DATA WAREHOUSE
-- STEP 10: CREATE SILVER CLEAN EVENTS TABLE
-- ============================================

CREATE TABLE IF NOT EXISTS
    MY_FIRST_DB.SILVER.CLEAN_EVENTS
AS

SELECT
    TRY_TO_TIMESTAMP_NTZ(
        REPLACE(TRIM(EVENT_TIME), ' UTC', ''),
        'YYYY-MM-DD HH24:MI:SS'
    ) AS EVENT_TIME,

    LOWER(TRIM(EVENT_TYPE)) AS EVENT_TYPE,

    TRY_TO_NUMBER(TRIM(PRODUCT_ID))::NUMBER(38,0)
        AS PRODUCT_ID,

    TRY_TO_NUMBER(TRIM(CATEGORY_ID))::NUMBER(38,0)
        AS CATEGORY_ID,

    NULLIF(TRIM(CATEGORY_CODE), '')
        AS CATEGORY_CODE,

    NULLIF(TRIM(BRAND), '')
        AS BRAND,

    TRY_TO_DECIMAL(TRIM(PRICE), 18, 2)
        AS PRICE,

    TRY_TO_NUMBER(TRIM(USER_ID))::NUMBER(38,0)
        AS USER_ID,

    NULLIF(TRIM(USER_SESSION), '')
        AS USER_SESSION

FROM MY_FIRST_DB.BRONZE.RAW_EVENTS;