
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 25: GOLD METRICS SANITY CHECK
-- ============================================

-- 1. DAILY SALES METRICS

SELECT
    'DAILY_SALES' AS TABLE_NAME,
    COUNT_IF(
        TOTAL_PURCHASE_EVENTS < 0
        OR UNIQUE_BUYERS < 0
        OR PURCHASE_SESSIONS < 0
        OR TOTAL_REVENUE < 0
        OR AVG_PURCHASE_VALUE < 0
    ) AS INVALID_ROWS
FROM MY_FIRST_DB.GOLD.DAILY_SALES

UNION ALL

-- 2. PRODUCT PERFORMANCE METRICS

SELECT
    'PRODUCT_PERFORMANCE',
    COUNT_IF(
        TOTAL_VIEWS < 0
        OR TOTAL_CART_EVENTS < 0
        OR TOTAL_PURCHASE_EVENTS < 0
        OR TOTAL_REVENUE < 0
        OR UNIQUE_USERS < 0
    )
FROM MY_FIRST_DB.GOLD.PRODUCT_PERFORMANCE

UNION ALL

-- 3. CUSTOMER BEHAVIOR METRICS

SELECT
    'CUSTOMER_BEHAVIOR',
    COUNT_IF(
        TOTAL_EVENTS < 0
        OR TOTAL_VIEWS < 0
        OR TOTAL_CART_EVENTS < 0
        OR TOTAL_PURCHASE_EVENTS < 0
        OR TOTAL_REVENUE < 0
        OR TOTAL_SESSIONS < 0
    )
FROM MY_FIRST_DB.GOLD.CUSTOMER_BEHAVIOR;


-- 4. CUSTOMER EVENT COUNT RECONCILIATION

SELECT
    COUNT_IF(
        TOTAL_EVENTS <>
        TOTAL_VIEWS
        + TOTAL_CART_EVENTS
        + TOTAL_PURCHASE_EVENTS
    ) AS EVENT_COUNT_MISMATCHES
FROM MY_FIRST_DB.GOLD.CUSTOMER_BEHAVIOR;


-- 5. DAILY SALES DATE COVERAGE

SELECT
    COUNT(*) AS AVAILABLE_DATES,
    MIN(SALES_DATE) AS FIRST_DATE,
    MAX(SALES_DATE) AS LAST_DATE
FROM MY_FIRST_DB.GOLD.DAILY_SALES;
