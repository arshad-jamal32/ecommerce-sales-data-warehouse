-- STEP 19: GOLD LAYER QUALITY AUDIT
-- ============================================

SELECT
    'DAILY_SALES' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(SALES_DATE IS NULL) AS NULL_KEY_ROWS,
    COUNT_IF(
        TOTAL_PURCHASE_EVENTS IS NULL
        OR TOTAL_REVENUE IS NULL
        OR UNIQUE_BUYERS IS NULL
    ) AS NULL_METRIC_ROWS
FROM MY_FIRST_DB.GOLD.DAILY_SALES

UNION ALL

SELECT
    'PRODUCT_PERFORMANCE',
    COUNT(*),
    COUNT_IF(PRODUCT_ID IS NULL),
    COUNT_IF(
        TOTAL_VIEWS IS NULL
        OR TOTAL_CART_EVENTS IS NULL
        OR TOTAL_PURCHASE_EVENTS IS NULL
        OR TOTAL_REVENUE IS NULL
    )
FROM MY_FIRST_DB.GOLD.PRODUCT_PERFORMANCE

UNION ALL

SELECT
    'CUSTOMER_BEHAVIOR',
    COUNT(*),
    COUNT_IF(USER_ID IS NULL),
    COUNT_IF(
        TOTAL_EVENTS IS NULL
        OR TOTAL_VIEWS IS NULL
        OR TOTAL_CART_EVENTS IS NULL
        OR TOTAL_PURCHASE_EVENTS IS NULL
        OR TOTAL_REVENUE IS NULL
    )
FROM MY_FIRST_DB.GOLD.CUSTOMER_BEHAVIOR

UNION ALL

SELECT
    'CONVERSION_FUNNEL',
    COUNT(*),
    0,
    COUNT_IF(
        TOTAL_SESSIONS_ANALYZED IS NULL
        OR SESSIONS_WITH_VIEW IS NULL
        OR SESSIONS_WITH_CART IS NULL
        OR SESSIONS_WITH_PURCHASE IS NULL
    )
FROM MY_FIRST_DB.GOLD.CONVERSION_FUNNEL;
