
-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 30: STREAM + MERGE INCREMENTAL PIPELINE
-- ============================================

-- 1. Create an independent target table
CREATE TABLE IF NOT EXISTS
    MY_FIRST_DB.SILVER.DIM_PRODUCTS_INCREMENTAL_DEMO
CLONE
    MY_FIRST_DB.SILVER.DIM_PRODUCTS;


-- 2. Apply captured stream changes using MERGE
-- INSERT records include both new rows and updated row versions.

MERGE INTO
    MY_FIRST_DB.SILVER.DIM_PRODUCTS_INCREMENTAL_DEMO AS TARGET

USING
(
    SELECT
        PRODUCT_ID,
        CATEGORY_ID,
        CATEGORY_CODE,
        BRAND,
        BRAND_VARIANT_COUNT,
        BRAND_CONFLICT_FLAG
    FROM MY_FIRST_DB.SILVER.PRODUCTS_CHANGE_STREAM
    WHERE METADATA$ACTION = 'INSERT'
) AS SOURCE

ON TARGET.PRODUCT_ID = SOURCE.PRODUCT_ID

WHEN MATCHED THEN
    UPDATE SET
        TARGET.CATEGORY_ID = SOURCE.CATEGORY_ID,
        TARGET.CATEGORY_CODE = SOURCE.CATEGORY_CODE,
        TARGET.BRAND = SOURCE.BRAND,
        TARGET.BRAND_VARIANT_COUNT = SOURCE.BRAND_VARIANT_COUNT,
        TARGET.BRAND_CONFLICT_FLAG = SOURCE.BRAND_CONFLICT_FLAG

WHEN NOT MATCHED THEN
    INSERT
    (
        PRODUCT_ID,
        CATEGORY_ID,
        CATEGORY_CODE,
        BRAND,
        BRAND_VARIANT_COUNT,
        BRAND_CONFLICT_FLAG
    )
    VALUES
    (
        SOURCE.PRODUCT_ID,
        SOURCE.CATEGORY_ID,
        SOURCE.CATEGORY_CODE,
        SOURCE.BRAND,
        SOURCE.BRAND_VARIANT_COUNT,
        SOURCE.BRAND_CONFLICT_FLAG
    );


-- 3. Verify updated product
SELECT *
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS_INCREMENTAL_DEMO
WHERE PRODUCT_ID = 1005115;


-- 4. Verify inserted product
SELECT *
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS_INCREMENTAL_DEMO
WHERE PRODUCT_ID = 999999999998;


-- 5. Verify target table row count
SELECT COUNT(*) AS TOTAL_PRODUCTS
FROM MY_FIRST_DB.SILVER.DIM_PRODUCTS_INCREMENTAL_DEMO;


-- 6. Check whether stream changes were consumed
SELECT COUNT(*) AS REMAINING_STREAM_CHANGES
FROM MY_FIRST_DB.SILVER.PRODUCTS_CHANGE_STREAM;
