-- E-COMMERCE DATA WAREHOUSE
-- STEP 12: INVESTIGATE MULTIPLE PRODUCT BRANDS
-- ============================================

SELECT
    PRODUCT_ID,

    COUNT(*) AS TOTAL_EVENTS,

    COUNT(DISTINCT BRAND) AS BRAND_VARIANTS,

    LISTAGG(DISTINCT BRAND, ', ')
        WITHIN GROUP (ORDER BY BRAND) AS BRANDS_FOUND

FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS

GROUP BY PRODUCT_ID

HAVING COUNT(DISTINCT BRAND) > 1

ORDER BY BRAND_VARIANTS DESC, PRODUCT_ID

LIMIT 30;