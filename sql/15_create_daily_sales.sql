-- ============================================
-- E-COMMERCE DATA WAREHOUSE
-- STEP 15: GOLD DAILY SALES
-- ============================================

CREATE TABLE IF NOT EXISTS
    MY_FIRST_DB.GOLD.DAILY_SALES
AS

SELECT
    CAST(EVENT_TIME AS DATE) AS SALES_DATE,

    COUNT(*) AS TOTAL_PURCHASE_EVENTS,

    SUM(PRICE) AS TOTAL_REVENUE,

    COUNT(DISTINCT USER_ID) AS UNIQUE_BUYERS,

    COUNT(DISTINCT USER_SESSION) AS PURCHASE_SESSIONS,

    ROUND(AVG(PRICE), 2) AS AVG_PURCHASE_VALUE

FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS

WHERE EVENT_TYPE = 'purchase'

GROUP BY CAST(EVENT_TIME AS DATE)

ORDER BY SALES_DATE;