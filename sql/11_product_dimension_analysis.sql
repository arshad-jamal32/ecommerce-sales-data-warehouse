WITH PRODUCT_PROFILE AS
(
    SELECT
        PRODUCT_ID,

        COUNT(DISTINCT CATEGORY_ID)
            AS CATEGORY_ID_VARIANTS,

        COUNT(DISTINCT CATEGORY_CODE)
            AS CATEGORY_CODE_VARIANTS,

        COUNT(DISTINCT BRAND)
            AS BRAND_VARIANTS

    FROM MY_FIRST_DB.SILVER.CLEAN_EVENTS

    GROUP BY PRODUCT_ID
)

SELECT
    COUNT(*) AS TOTAL_UNIQUE_PRODUCTS,

    COUNT_IF(CATEGORY_ID_VARIANTS > 1)
        AS PRODUCTS_WITH_MULTIPLE_CATEGORY_IDS,

    COUNT_IF(CATEGORY_CODE_VARIANTS > 1)
        AS PRODUCTS_WITH_MULTIPLE_CATEGORY_CODES,

    COUNT_IF(BRAND_VARIANTS > 1)
        AS PRODUCTS_WITH_MULTIPLE_BRANDS

FROM PRODUCT_PROFILE;