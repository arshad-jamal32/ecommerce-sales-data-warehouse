-- STEP 37: RESTORE DATA USING TIME TRAVEL
-- ============================================

-- Restore Rahul's original balance
UPDATE MY_FIRST_DB.SILVER.TIME_TRAVEL_DEMO AS CURRENT_DATA
SET BALANCE = HISTORICAL_DATA.BALANCE
FROM
(
    SELECT CUSTOMER_ID, BALANCE
    FROM MY_FIRST_DB.SILVER.TIME_TRAVEL_DEMO
    AT (
        TIMESTAMP =>
        TO_TIMESTAMP_TZ('2026-11-23 09:40:32.891000-08:00')
    )
) AS HISTORICAL_DATA
WHERE CURRENT_DATA.CUSTOMER_ID = HISTORICAL_DATA.CUSTOMER_ID;

-- Restore Priya's deleted record
INSERT INTO MY_FIRST_DB.SILVER.TIME_TRAVEL_DEMO
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    BALANCE
)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    BALANCE
FROM MY_FIRST_DB.SILVER.TIME_TRAVEL_DEMO
AT (
    TIMESTAMP =>
    TO_TIMESTAMP_TZ('2026-11-23 09:40:32.891000-08:00')
)
WHERE CUSTOMER_ID = 2
AND NOT EXISTS
(
    SELECT 1
    FROM MY_FIRST_DB.SILVER.TIME_TRAVEL_DEMO CURRENT_DATA
    WHERE CURRENT_DATA.CUSTOMER_ID = 2
);

-- Verify restored table
SELECT *
FROM MY_FIRST_DB.SILVER.TIME_TRAVEL_DEMO
ORDER BY CUSTOMER_ID;
